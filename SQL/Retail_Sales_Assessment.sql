-- Q2. REMOVE DUPLICATE ORDER LINES
-- Preserve raw OrderItems; create a cleaned working copy.
-- Keep the latest LoadedAt row for each OrderItemID.


CREATE TABLE OrderItems_Clean AS
SELECT
    OrderItemID,
    OrderID,
    ProductID,
    Quantity,
    UnitPrice,
    LoadedAt
FROM (
    SELECT
        oi.*,
        ROW_NUMBER() OVER (
            PARTITION BY OrderItemID
            ORDER BY LoadedAt DESC
        ) AS rn
    FROM OrderItems AS oi
) AS ranked
WHERE rn = 1;

