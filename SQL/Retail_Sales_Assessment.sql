-- Q9. COMPARE REGIONS
-- Gross-sales rank and net-sales rank, with returns deducted.

WITH RegionalSales AS (
    SELECT
        r.RegionName,
        SUM(oi.Quantity * oi.UnitPrice) AS GrossSales
    FROM Orders AS o
    JOIN Stores AS s
        ON o.StoreID = s.StoreID
    JOIN Regions AS r
        ON s.RegionID = r.RegionID
    JOIN OrderItems_Clean AS oi
        ON oi.OrderID = o.OrderID
    WHERE o.OrderStatus = 'Completed'
      AND o.OrderDate >= '2026-10-01'
      AND o.OrderDate < '2026-11-01'
    GROUP BY r.RegionName
),
RegionalReturns AS (
    SELECT
        r.RegionName,
        SUM(rt.ReturnQuantity * oi.UnitPrice) AS ReturnValue
    FROM Returns AS rt
    JOIN OrderItems_Clean AS oi
        ON rt.OrderItemID = oi.OrderItemID
    JOIN Orders AS o
        ON oi.OrderID = o.OrderID
    JOIN Stores AS s
        ON o.StoreID = s.StoreID
    JOIN Regions AS r
        ON s.RegionID = r.RegionID
    WHERE o.OrderStatus = 'Completed'
      AND rt.ReturnDate >= '2026-10-01'
      AND rt.ReturnDate < '2026-11-01'
    GROUP BY r.RegionName
),
RegionalNet AS (
    SELECT
        rs.RegionName,
        rs.GrossSales,
        COALESCE(rr.ReturnValue, 0) AS ReturnValue,
        rs.GrossSales - COALESCE(rr.ReturnValue, 0) AS NetSales
    FROM RegionalSales AS rs
    LEFT JOIN RegionalReturns AS rr
        ON rs.RegionName = rr.RegionName
)
SELECT
    RegionName,
    ROUND(GrossSales, 2) AS GrossSales,
    ROUND(ReturnValue, 2) AS ReturnValue,
    ROUND(NetSales, 2) AS NetSales,
    RANK() OVER (ORDER BY GrossSales DESC) AS GrossSalesRank,
    RANK() OVER (ORDER BY NetSales DESC) AS NetSalesRank
FROM RegionalNet
ORDER BY NetSalesRank, RegionName;


